import streamlit as st


def show_dialogue(location, speaker, words):
    # 모든 장면에서 같은 위치와 크기의 화면을 사용
    st.caption("CHAPTER 01")
    st.title("낯선 의뢰")

    with st.container(border=True):
        # 나중에 배경과 캐릭터 이미지를 추가할 공간
        with st.container(height=280, border=False):
            st.caption(location)
            st.caption("배경 및 캐릭터 이미지 영역")

        # 한 번에 한 사람의 대사만 표시
        with st.container(height=140, border=True):
            st.markdown("**" + speaker + "**")
            st.write(words)


